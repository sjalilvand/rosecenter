def dir_for(locale):
    return "rtl" if is_rtl(locale) else "ltr"


FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
AR_DIGITS = "٠١٢٣٤٥٦٧٨٩"


def to_digits(value, locale):
    """تبدیل ارقام لاتین به ارقام بومی زبان (فارسی/عربی)"""
    s = str(value)
    if locale == "fa":
        return s.translate(str.maketrans("0123456789", FA_DIGITS))
    if locale == "ar":
        return s.translate(str.maketrans("0123456789", AR_DIGITS))
    return s



DICTS = {"fa": fa, "en": en, "ar": ar, "ru": ru, "zh": zh}


def t(key, locale=DEFAULT_LOCALE, fallback=""):
    """ترجمه یک کلید — زنجیرهٔ پشتیبان: زبان فعال → فارسی → fallback → کلید"""
    d = DICTS.get(locale) or fa
    v = d.get(key)
    if v is None:
        v = fa.get(key)
    if v is None:
        v = fallback or key
    return v


